// Generates the three registry index files from the files in their folders.
//   node scripts/gen-registry.mjs          write the index files
//   node scripts/gen-registry.mjs --check  exit 1 if any index file is out of date
//   --root <dir>                           act on another checkout (used by CI)
// Every .js file directly inside a registry folder (other than index.js) is a module with a default export.
// Helpers belong in a subfolder or elsewhere. Run `npm run registry` after adding, renaming or removing a module.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const REGISTRIES = [
  { dir: 'src/sim/systems', exportName: 'systems' },
  { dir: 'src/render/systems', exportName: 'renderSystems' },
  { dir: 'src/ui/modules', exportName: 'uiModules' },
];

const camel = (file) => {
  const n = file.replace(/\.js$/, '').replace(/[-_.]+([a-z0-9])/gi, (_, c) => c.toUpperCase());
  return /^[a-z_$]/i.test(n) ? n : 'm' + n;
};

export function render({ dir, exportName }, root) {
  const files = readdirSync(join(root, dir), { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith('.js') && e.name !== 'index.js')
    .map((e) => e.name)
    .sort();
  const names = files.map(camel);
  if (new Set(names).size !== names.length) throw new Error(dir + ': two files map to the same identifier');
  for (const f of files) {
    if (!/^export default\b/m.test(readFileSync(join(root, dir, f), 'utf8'))) throw new Error(dir + '/' + f + ': needs a default export (move helpers out of this folder)');
  }
  return [
    '// GENERATED by scripts/gen-registry.mjs (npm run registry). Do not edit by hand.',
    '// To add a feature, create a file in this folder with a default export, then run `npm run registry`.',
    '// Hook shapes are documented in docs/EXTENDING.md. Modules run in order of their optional `order` number, then file name.',
    ...files.map((f, i) => `import ${names[i]} from './${f}';`),
    '',
    `export const ${exportName} = [`,
    ...names.map((n) => `  ${n},`),
    '];',
    '',
  ].join('\n');
}

export function generate(root) {
  return REGISTRIES.map((r) => ({ path: join(r.dir, 'index.js'), content: render(r, root) }));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const ri = process.argv.indexOf('--root');
  const root = ri > 0 ? resolve(process.argv[ri + 1]) : resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const stale = [];
  for (const { path, content } of generate(root)) {
    let cur = '';
    try { cur = readFileSync(join(root, path), 'utf8'); } catch { /* missing */ }
    if (cur === content) continue;
    if (process.argv.includes('--check')) stale.push(path); else { writeFileSync(join(root, path), content); console.log('wrote ' + path); }
  }
  if (stale.length) { console.error('Out of date (run npm run registry): ' + stale.join(', ')); process.exit(1); }
}
