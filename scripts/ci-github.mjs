// Shared by scripts/ci-pr.mjs and scripts/ci-notify-behind.mjs. Node 22 built-ins only: GitHub REST through fetch.
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';

export function repo() {
  if (!process.env.GITHUB_REPOSITORY) throw new Error('GITHUB_REPOSITORY is not set');
  return process.env.GITHUB_REPOSITORY;
}

export async function api(path, { method = 'GET', body } = {}) {
  const res = await fetch(`https://api.github.com/repos/${repo()}${path}`, {
    method,
    headers: {
      authorization: `Bearer ${process.env.GITHUB_TOKEN}`,
      accept: 'application/vnd.github+json',
      'x-github-api-version': '2022-11-28',
      ...(body ? { 'content-type': 'application/json' } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  if (!res.ok) throw new Error(`${method} ${path} failed: ${res.status} ${await res.text()}`);
  return res.status === 204 ? null : res.json();
}

// Every page of a list endpoint. `path` may already carry a query string.
export async function listAll(path) {
  const out = [];
  const sep = path.includes('?') ? '&' : '?';
  for (let page = 1; ; page++) {
    const rows = await api(`${path}${sep}per_page=100&page=${page}`);
    out.push(...rows);
    if (rows.length < 100) return out;
  }
}

// The first comment on an issue or PR whose body contains `marker`.
export async function findComment(issue, marker) {
  return (await listAll(`/issues/${issue}/comments`)).find((c) => c.body?.includes(marker));
}

// A new comment notifies people. Editing one does not, so status comments are edited in place.
export const addComment = (issue, body) => api(`/issues/${issue}/comments`, { method: 'POST', body: { body: body + FOOTER } });
export const editComment = (id, body) => api(`/issues/comments/${id}`, { method: 'PATCH', body: { body: body + FOOTER } });
